def _jsonld(obj: dict) -> str:
    # «</» внутри JSON закрыло бы тег script — экранируем
    return '<script type="application/ld+json">' + json.dumps(obj, ensure_ascii=False).replace("</", "<\\/") + "</script>"


def _layout(site: str, path: str, title: str, description: str, body: str, ld: list[dict]) -> str:
    url = f"{site}{path}"
    return (
        '<!doctype html><html lang="ru"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>{escape(title)}</title>"
        f'<meta name="description" content="{escape(description)}">'
        f'<link rel="canonical" href="{escape(url)}">'
        '<meta name="robots" content="index,follow,max-image-preview:large">'
        '<meta property="og:type" content="article"><meta property="og:locale" content="ru_RU">'
        f'<meta property="og:site_name" content="{SITE_NAME}">'
        f'<meta property="og:title" content="{escape(title)}">'
        f'<meta property="og:description" content="{escape(description)}">'
        f'<meta property="og:url" content="{escape(url)}">'
        f'<meta property="og:image" content="{site}/icons/og-image.png">'
        '<meta property="og:image:width" content="1200"><meta property="og:image:height" content="630">'
        '<meta name="twitter:card" content="summary_large_image">'
        '<link rel="icon" type="image/png" sizes="192x192" href="/icons/icon-192.png">'
        '<meta name="theme-color" content="#2F6B4F">'
        f"<style>{_CSS}</style>" + "".join(_jsonld(x) for x in ld) +
        f'</head><body><main class="wrap">{body}'
        f'<footer>© {SITE_NAME} · <a href="/">Открыть помощника</a> · <a href="/pitanie">Все статьи</a></footer>'
        "</main></body></html>"
    )


def _crumbs(site: str, items: list[tuple[str, str]]) -> dict:
    return {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i + 1, "name": name, "item": f"{site}{path}"}
        for i, (name, path) in enumerate(items)]}


def render_page(slug: str, site: str) -> str | None:
    p = PAGES.get(slug)
    if not p:
        return None
    path = f"/pitanie/{slug}"
    body = ['<nav class="crumbs"><a href="/">Главная</a> › <a href="/pitanie">Питание и рецепты</a></nav>',
            f"<h1>{escape(p['h1'])}</h1>", f'<p class="lead">{escape(p["intro"])}</p>',
            '<a class="cta" href="/">🍳 Открыть помощника — бесплатно</a>']
    for h, text in p["sections"]:
        body.append(f"<h2>{escape(h)}</h2><p>{escape(text)}</p>")
    if p["faq"]:
        body.append('<h2>Частые вопросы</h2><div class="card">')
        body += [f"<details><summary>{escape(q)}</summary><p>{escape(a)}</p></details>" for q, a in p["faq"]]
        body.append("</div>")
    others = [(s, o["h1"]) for s, o in PAGES.items() if s != slug][:6]
    body.append('<h2>Ещё по теме</h2><ul class="links">' +
                "".join(f'<li><a href="/pitanie/{s}">{escape(t)}</a></li>' for s, t in others) + "</ul>")
    body.append('<a class="cta" href="/">Составить рецепт или меню</a>')
    ld = [
        {"@context": "https://schema.org", "@type": "WebPage", "name": p["title"], "description": p["description"],
         "url": f"{site}{path}", "inLanguage": "ru",
         "isPartOf": {"@type": "WebSite", "name": SITE_NAME, "url": f"{site}/"}},
        _crumbs(site, [("Главная", "/"), ("Питание и рецепты", "/pitanie"), (p["h1"], path)]),
    ]
    if p["faq"]:
        ld.append({"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": [
            {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in p["faq"]]})
    return _layout(site, path, p["title"], p["description"], "".join(body), ld)


