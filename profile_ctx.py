"""
Что исключить из блюд в ТЕКУЩЕМ запросе (поле «Исключить» анкеты) — для усиленной подсказки ИИ и проверки ответа.

Ничего о человеке в базе не хранится: список приходит вместе с запросом. Сборщики промптов (prompts.py, missing.py)
кладут его в contextvar перед обращением к ИИ, а ai.call_llm_with_fallback — единственная точка, через которую идут
ВСЕ генерации, — дописывает его в запрос и проверяет ответ. asyncio-задачи копируют контекст при создании.
"""
import contextvars
import re

current = contextvars.ContextVar("cooking_avoid", default=None)
base = contextvars.ContextVar("cooking_avoid_base", default="")      # список «никогда не использовать» из профиля


def _split(text: str) -> list[str]:
    out = []
    for x in re.split(r"[,;\n]+", (text or "").lower()):
        x = x.strip(" .-")
        if x and x not in out and x not in ("нет", "ничего"):
            out.append(x[:40])
    return out


def _join_capped(items: list[str], limit: int = 500) -> str:
    """Склеивает пункты через ", ", не обрезая строку посередине пункта (до 2026-11-12: жёсткий
    срез [:500] мог отрезать последний продукт на середине слова и вместе с ним потерять предыдущие
    пункты из ВИДА проверки — например, «молоко, орехи, морепрод» вместо «молоко, орехи» целиком)."""
    out = ""
    for it in items:
        add = (", " if out else "") + it
        if len(out) + len(add) > limit:
            break
        out += add
    return out


def set_user(uid) -> None:
    """Список «никогда не использовать» человека: только если он в тарифе (функция «память») и дал согласие."""
    import accounts
    import plans
    txt = ""
    try:
        g = accounts.goals_get(uid)
        if "never" in g["feats"] and accounts.consent_get(uid) and plans.has_feature(uid, "memory"):
            txt = g["never"]
    except Exception:  # noqa: BLE001 — сбой базы не должен ломать подбор
        txt = ""
    base.set(txt)
    items = _split(txt)
    current.set({"never": _join_capped(items)} if items else None)


def set_avoid(text) -> None:
    """Список из поля «Исключить» запроса (через запятую) плюс список из профиля. Пусто — проверка не нужна."""
    items = _split(base.get()) + [x for x in _split(text) if x not in _split(base.get())]
    current.set({"never": _join_capped(items)} if items else None)


def _items(p: dict) -> list[str]:
    return _split(p.get("never") or "")


def prompt_block() -> str:
    p = current.get()
    if not p:
        return ""
    return ("\n\nПРОДУКТЫ, КОТОРЫЕ ПОЛЬЗОВАТЕЛЬ ПРОСИЛ ИСКЛЮЧИТЬ — ЭТО ВАЖНЕЕ ЛЮБЫХ ДРУГИХ ПРАВИЛ И ПОЖЕЛАНИЙ: "
            f"{p['never']}. Не используй их и всё, что их содержит (соусы, заправки, посыпки, готовые смеси, замены "
            "«по вкусу»), ни в одном блюде, даже как добавку.")


def _pattern(word: str) -> re.Pattern:
    """«молоко» -> молок + до 4 букв окончания: молоко/молока/молоком, но не «молотый»; «орехи» -> орехов/ореховая."""
    w = word.lower().replace("ё", "е")
    if len(w) >= 4 and w[-1] in "аеиоуыэюяйь":
        w = w[:-1]
    return re.compile(r"(?<![а-я])(?<!без )(?<!не )" + re.escape(w) + r"[а-я]{0,4}(?![а-я])")


# Категории-исключения ловятся по конкретным продуктам, которые к ним относятся (решение от 2026-11-12):
# раньше hits() проверял только ПЕРВОЕ слово пункта — «молочные продукты» искало лишь «молочн*» и не ловило
# «молоко», «сыр», «творог»; «морепродукты» не ловило «креветки». Список заведомо неполный (это не замена
# точному перечню продуктов в «Исключить»), но закрывает самые частые категории-аллергены.
_CATEGORY_WORDS = {
    "молочн": ["молок", "молоч", "сыр(?:а|у|ом|е|ы|ов|ами|ах|ный|ная|ное|ные|ного|ной|ным|ными|ник|ники|ников)?",
               "творог", "творож", "кефир", "сливк", "сливоч", "йогурт", "сметан", "ряженк"],
    "морепродукт": ["кревет", "кальмар", "миди", "устриц", "краб", "осьминог", "гребеш"],
    "орех": ["миндал", "фундук", "кешью", "грецк", "арахис", "фисташ", "пекан"],
    "глютен": ["пшениц", "пшенич", "ржан", "ячмен", "ячнев", "манн", "макарон", "спагетти", "лапш", "хлеб",
               "булгур", "кускус", "перлов", "панировоч", "сухар"],
}
# Слова, которые сами по себе ничего не исключают: «Продукты» есть в заголовке каждого рецепта, «без» — в «без крышки».
_STOP = {"без", "для", "все", "что", "или", "при", "как", "так", "его", "это", "любые", "любой", "любая", "виде",
         "продукты", "продукт", "продуктов", "блюда", "блюдо", "еда", "еды", "которые", "очень", "много", "сильно",
         "содержащие", "содержат", "добавки"}
_NEG = r"(?<![а-я])(?<!без )(?<!не )"


def hits(text: str) -> list[str]:
    """Исключённые продукты, которые всё же встретились в ответе (кроме «без орехов», «не добавляй молоко»
    и строк вида «исключено: …»)."""
    p = current.get()
    if not p or not text:
        return []
    t = "\n".join(ln for ln in text.lower().replace("ё", "е").splitlines()
                  if not any(x in ln for x in ("исключ", "аллерг", "профил")))
    found = []
    for item in _items(p):
        # Раньше — только первое слово пункта; теперь — любое значимое слово (многословные пункты вроде
        # «курица и рыба» ловили только «курицу», рыбу пропускали).
        # «без глютена», «без сахара» — исключается то, что после «без»; служебные слова не ищем.
        words = [w.strip("«»\"()") for w in item.replace("ё", "е").split()]
        words = [w for w in words if len(w) >= 3 and w not in _STOP]
        if any(_pattern(w).search(t) for w in words):
            found.append(item)
            continue
        for cat, stems in _CATEGORY_WORDS.items():
            if cat in item.replace("ё", "е") and any(re.search(_NEG + s + (r"(?![а-я])" if "(" in s else ""), t) for s in stems):
                found.append(item)
                break
    return found
