def portion_instruction(data: dict) -> str:
    """Строка для промпта про размер порции ('' для обычной). Явная цель по КБЖУ важнее размера порции."""
    text = _PORTION_TEXT.get((data or {}).get("portion") or DEFAULT_PORTION)
    if not text:
        return ""
    return f"- РАЗМЕР ПОРЦИИ: {text} Если задана цель по КБЖУ, она важнее — попадай в неё.\n"
