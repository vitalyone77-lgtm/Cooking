def in_category(cat: int) -> list[dict]:
    return [f for f in FOODS if f["cat"] == cat]


def search(query: str, limit: int = 10) -> list[dict]:
    q = (query or "").lower().replace("ё", "е").strip()
    if len(q) < 2:
        return []
    words = q.split()
    found = [f for f in FOODS if all(w in f["name"].lower().replace("ё", "е") for w in words)]
    return found[:limit]


def nutrition(food: dict, grams: float) -> dict:
    """КБЖУ на указанный вес."""
    k = grams / 100.0
    return {"kcal": int(round(food["kcal100"] * k)), "protein": round(food["p100"] * k, 1),
            "fat": round(food["f100"] * k, 1), "carb": round(food["c100"] * k, 1)}


def portion_kcal(food: dict) -> int:
    return nutrition(food, food["grams"])["kcal"]
