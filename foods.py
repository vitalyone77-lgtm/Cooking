def content_words(text: str) -> list[str]:
    """Слова запроса без служебных: «суп из курицы» -> суп, курицы."""
    return [w for w in _tokens(text) if len(w) >= 2 and w not in _STOP]


def _stem(w: str) -> str:
    """«курицу» -> «кури», «картошка» -> «картош»: ищем слова, которые начинаются так же."""
    if len(w) <= 3:
        return w
    if len(w) <= 5:
        return w[:len(w) - 1]
    return w[:max(4, len(w) - 2)]


def search(query: str, limit: int = 10) -> list[dict]:
    """Поиск по названию и синонимам: каждое слово запроса должно начинаться как слово продукта (склонения, «картошка»).
    Если ничего нет, пробуем поправить опечатки («греча», «крица»)."""
    words = content_words(query)
    if not words:
        return []

    def run(ws: list[str]) -> list[dict]:
        out = []
        for f in FOODS:
            hit = 0
            for w in ws:
                st = _stem(w)
                if any(t.startswith(st) for t in f["tokens"]):
                    hit += 1
            if hit == len(ws):
                first = _norm(f["name"]).startswith(_stem(ws[0]))
                dry = 1 if "сух" in _norm(f["name"]) else 0          # готовые (варёные) блюда чаще, чем сухие крупы
                out.append((0 if first else 1, dry, len(f["name"]), f))
        out.sort(key=lambda x: (x[0], x[1], x[2]))
        return [x[3] for x in out]

    found = run(words)
    if not found:
        fixed = []
        for w in words:
            near = difflib.get_close_matches(w, _VOCAB, n=1, cutoff=0.72) if len(w) >= 3 else []
            fixed.append(near[0] if near else w)
        if fixed != words:
            found = run(fixed)
    return found[:limit]


def nutrition(food: dict, grams: float) -> dict:
    """КБЖУ на указанный вес."""
    k = grams / 100.0
    return {"kcal": int(round(food["kcal100"] * k)), "protein": round(food["p100"] * k, 1),
            "fat": round(food["f100"] * k, 1), "carb": round(food["c100"] * k, 1)}


def portion_kcal(food: dict) -> int:
    return nutrition(food, food["grams"])["kcal"]


